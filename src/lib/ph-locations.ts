export interface RegionInfo {
  id: string;       // app region id (ncr | car | region-1 … region-13 | barmm)
  name: string;     // PSGC region name
  shortName: string; // e.g. "NCR", "Region VII"
  tagline: string;  // homepage tagline used per region
}

export interface ProvinceInfo {
  id: string;       // PSGC province code
  name: string;     // province name ("Metro Manila" for NCR)
  region: string;   // app region id
}

export interface CityLocation {
  id: string;       // 7-digit PSGC city/municipality code
  name: string;     // normalized display name (unique within province)
  province: string; // province name (geographic province for HUCs)
  region: string;   // app region id
  isCity: boolean;  // true = city, false = municipality
}

