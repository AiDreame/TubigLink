/** Lookup maps (built once at module load). */
const REGION_BY_ID = new Map(PH_REGIONS.map((r) => [r.id, r]));
const PROVINCES_BY_NAME = new Map(PH_PROVINCES.map((p) => [p.name, p]));
const PROVINCES_BY_REGION = new Map<string, ProvinceInfo[]>();
for (const p of PH_PROVINCES) {
  const list = PROVINCES_BY_REGION.get(p.region) ?? [];
  list.push(p);
  PROVINCES_BY_REGION.set(p.region, list);
}

/**
 * Normalize a city/province/region name for matching:
 * trims, collapses whitespace, strips diacritics and punctuation,
 * lowercases. "Parañaque" → "paranaque", "Buena Vista" → "buenavista",
 * "Lapu-Lapu" → "lapulapu".
 */
export function normalizeCityName(input: string): string {
  return input
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // strip diacritics (ñ → n, á → a)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ""); // drop spaces, punctuation, hyphens
}

/** Alias — search keys are just normalized names. */
export const normalizeSearchKey = normalizeCityName;

/** Region helpers. */
export function regionName(regionId: string): string {
  return REGION_BY_ID.get(regionId)?.name ?? regionId;
}
export function regionShortName(regionId: string): string {
  return REGION_BY_ID.get(regionId)?.shortName ?? regionId;
}
export function regionTagline(regionId: string): string {
  return REGION_BY_ID.get(regionId)?.tagline ?? "";
}
export function provinceRegion(provinceName: string): string {
  return PROVINCES_BY_NAME.get(provinceName)?.region ?? "";
}

/** All cities/municipalities of a province. */
export function citiesByProvince(provinceName: string): CityLocation[] {
  return PH_CITIES_MUNICIPALITIES.filter((c) => c.province === provinceName);
}

/** Provinces of a region (ordered by name). */
export function provincesByRegion(regionId: string): ProvinceInfo[] {
  return [...(PROVINCES_BY_REGION.get(regionId) ?? [])].sort((a, b) =>
    a.name.localeCompare(b.name)
  );
}

/**
 * Find a city by its display name. Exact normalized match wins; ties prefer
 * NCR/Metro Manila, then cities over municipalities. Falls back to a
 * substring match so legacy spellings ("Buena Vista") still resolve.
 */
export function getCityByName(name: string): CityLocation | undefined {
  const key = normalizeCityName(name);
  if (!key) return undefined;
  const exact = PH_CITIES_MUNICIPALITIES.filter((c) => normalizeCityName(c.name) === key);
  if (exact.length > 0) {
    return (
      exact.find((c) => c.region === "ncr") ??
      exact.find((c) => c.isCity) ??
      exact[0]
    );
  }
  return PH_CITIES_MUNICIPALITIES.find((c) => normalizeCityName(c.name).includes(key));
}

/** Region id for a city name (legacy helper used by the city store). */
export function getRegionForCity(cityName: string): string {
  return getCityByName(cityName)?.region ?? "ncr";
}

/** Region tagline for a city name (used by the homepage hero). */
export function getRegionTaglineForCity(cityName: string): string {
  const region = getCityByName(cityName)?.region;
  return region ? regionTagline(region) : "The Philippines' trusted water delivery service";
}

export interface CitySearchResult extends CityLocation {
  regionName: string;
  label: string; // "City · Province" for list rendering
}

/**
 * Search across city/municipality name, province, and region name.
 * Results are flat with region/province labels. Prefix/exact matches rank
 * first, then substring matches; capped at `limit` (default 60).
 */
export function searchCities(query: string, limit = 60): CitySearchResult[] {
  const q = normalizeSearchKey(query);
  if (!q) return [];
  const scored: Array<{ c: CityLocation; score: number }> = [];
  for (const c of PH_CITIES_MUNICIPALITIES) {
    const nameKey = normalizeSearchKey(c.name);
    const provKey = normalizeSearchKey(c.province);
    const regKey = normalizeSearchKey(regionName(c.region));
    if (nameKey === q) {
      scored.push({ c, score: 0 });
    } else if (nameKey.startsWith(q)) {
      scored.push({ c, score: 1 });
    } else if (nameKey.includes(q)) {
      scored.push({ c, score: 2 });
    } else if (provKey.startsWith(q) || provKey.includes(q)) {
      scored.push({ c, score: 3 });
    } else if (regKey.includes(q) || regionShortName(c.region).toLowerCase().includes(q)) {
      scored.push({ c, score: 4 });
    }
  }
  return scored
    .sort((a, b) => a.score - b.score || a.c.name.localeCompare(b.c.name))
    .slice(0, limit)
    .map(({ c }) => ({
      ...c,
      regionName: regionName(c.region),
      label: `${c.name} · ${c.province}`,
    }));
}

export interface ProvinceCityGroup {
  province: string;
  cities: CityLocation[];
}

export interface RegionCityGroup {
  regionId: string;
  regionName: string;
  provinces: ProvinceCityGroup[];
}

/**
 * Full list grouped by region → province, NCR ("Metro Manila") first,
 * regions in canonical PSGC order, cities/municipalities alphabetical.
 */
export function getCitiesGroupedByRegion(): RegionCityGroup[] {
  return PH_REGIONS.map((r) => {
    const provinces = provincesByRegion(r.id).map((p) => ({
      province: p.name,
      cities: citiesByProvince(p.name),
    }));
    return { regionId: r.id, regionName: r.name, provinces };
  });
}

